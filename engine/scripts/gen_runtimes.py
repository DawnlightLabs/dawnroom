"""Writes registry/runtimes/*.toml from the live GitHub release API: URL, size and sha256 come
from the release's asset digests, the unpacked size and file list from each zip's central
directory (read with HTTP Range requests, so nothing is downloaded whole). Never edit the
output by hand; re-run this when the pinned sd.cpp release changes.

    python engine/scripts/gen_runtimes.py
"""

import io
import json
import pathlib
import sys
import urllib.request
import zipfile

REPO = "leejet/stable-diffusion.cpp"
TAG = "master-1086-465adf3"
RUNTIME = "sd-cpp@" + TAG
SHORT = TAG.split("-")[-1]  # the commit, as the asset names spell it
UA = {"User-Agent": "dawnroom-runtime-generator"}

# Driver floors aren't in the release API. This build uses CUDA 12.8.1 (its build.yml at 465adf3
# installs cuda "12.8.1"; cudart64_12.dll in the cudart zip says 12.8.90). NVIDIA's CUDA Toolkit
# release notes, "CUDA Toolkit and Corresponding Driver Versions": 12.8 Update 1 needs
# >= 572.61 on Windows x86_64 (>= 570.124.06 on Linux). Checked 2026-11-16.
CUDA_DRIVER_SOURCE = "https://docs.nvidia.com/cuda/cuda-toolkit-release-notes/index.html (CUDA 12.8 Update 1 row; build.yml at 465adf3 installs CUDA 12.8.1)"

BUILDS = [
    # (build, os, gpu, experimental, asset names, min driver)
    ("windows-cuda12", "windows", "cuda", False,
     [f"sd-master-{SHORT}-bin-win-cuda12-x64.zip", "cudart-sd-bin-win-cu12-x64.zip"], "572.61"),
    ("windows-vulkan", "windows", "vulkan", True, [f"sd-master-{SHORT}-bin-win-vulkan-x64.zip"], None),
    ("linux-vulkan", "linux", "vulkan", True, [f"sd-master-{SHORT}-bin-Linux-Ubuntu-26.04-x86_64-vulkan.zip"], None),
]


class RangeFile(io.RawIOBase):
    """A read-only, seekable view of a remote file, fetched with HTTP Range requests."""

    def __init__(self, url, size):
        self.url, self.size, self.pos = url, size, 0

    def seekable(self):
        return True

    def readable(self):
        return True

    def tell(self):
        return self.pos

    def seek(self, off, whence=0):
        self.pos = {0: off, 1: self.pos + off, 2: self.size + off}[whence]
        return self.pos

    def read(self, n=-1):
        if n < 0:
            n = self.size - self.pos
        if n == 0 or self.pos >= self.size:
            return b""
        end = min(self.pos + n, self.size) - 1
        req = urllib.request.Request(self.url, headers={**UA, "Range": f"bytes={self.pos}-{end}"})
        with urllib.request.urlopen(req) as r:
            if r.status != 206:
                sys.exit(f"{self.url}: expected 206 for a Range request, got {r.status}")
            data = r.read()
        self.pos += len(data)
        return data


def final_url(url):
    req = urllib.request.Request(url, headers=UA, method="HEAD")
    with urllib.request.urlopen(req) as r:
        return r.url


def main():
    root = pathlib.Path(__file__).resolve().parents[2]
    out_dir = root / "registry" / "runtimes"
    out_dir.mkdir(parents=True, exist_ok=True)
    api = f"https://api.github.com/repos/{REPO}/releases/tags/{TAG}"
    rel = json.load(urllib.request.urlopen(urllib.request.Request(api, headers=UA)))
    assets = {a["name"]: a for a in rel["assets"]}

    for build, os_, gpu, experimental, names, min_driver in BUILDS:
        files, members = [], set()
        for name in names:
            a = assets.get(name) or sys.exit(f"{name} isn't in release {TAG}")
            digest = a.get("digest") or sys.exit(f"{name} has no digest in the release API")
            algo, sha = digest.split(":", 1)
            assert algo == "sha256", digest
            with zipfile.ZipFile(RangeFile(final_url(a["browser_download_url"]), a["size"])) as z:
                infos = [i for i in z.infolist() if not i.is_dir()]
                members |= {i.filename.replace("\\", "/") for i in infos}
                methods = {i.compress_type for i in infos}
                if not methods <= {zipfile.ZIP_STORED, zipfile.ZIP_DEFLATED}:
                    sys.exit(f"{name} uses compression {methods}; the engine only unpacks stored/deflate")
                unpacked = sum(i.file_size for i in infos)
            files.append((name, a["browser_download_url"], a["size"], sha, unpacked))
        exe = ".exe" if os_ == "windows" else ""
        server, cli = f"sd-server{exe}", f"sd-cli{exe}"
        for need in (server, cli):
            if need not in members:
                sys.exit(f"{build}: {need} isn't at the top of the zip(s); members start with {sorted(members)[:5]}")

        lines = [
            f"# Generated by engine/scripts/gen_runtimes.py from the GitHub release API ({REPO} {TAG}):",
            "# URL, size and sha256 from the asset digests, unpacked size from each zip's index. Never edit by hand.",
            "schema = 1",
            f'id = "{RUNTIME.replace("@", "-")}-{build}"',
            f'runtime = "{RUNTIME}"',
            f'build = "{build}"',
            f'os = "{os_}"',
            f'gpu = "{gpu}"',
            f"experimental = {str(experimental).lower()}",
            f'server = "{server}"',
            f'cli = "{cli}"',
        ]
        if os_ == "linux":
            # The Linux zips are built on Ubuntu 26.04 (glibc 2.43; checked with objdump on sd-cli).
            lines += ['min_glibc = "2.43"']
        if min_driver:
            lines += [f'min_driver = "{min_driver}"', f'min_driver_source = "{CUDA_DRIVER_SOURCE}"']
        for name, url, size, sha, unpacked in files:
            lines += ["", "[[files]]", f'name = "{name}"', f'url = "{url}"', f"size = {size}", f'sha256 = "{sha}"', f"unpacked_size = {unpacked}"]
        (out_dir / f"{build}.toml").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
        print(f"{build}: {len(files)} file(s), {sum(f[2] for f in files)} bytes download, {sum(f[4] for f in files)} unpacked")


if __name__ == "__main__":
    main()
